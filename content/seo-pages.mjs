  const image = origin + `/images/${page.image}.webp`;
  return `<meta name="robots" content="index,follow,max-image-preview:large" />\n<link rel="canonical" href="${origin + page.path}" />\n<meta property="og:type" content="website" />\n<meta property="og:site_name" content="SonkoFlow" />\n<meta property="og:title" content="${escape(page.title)}" />\n<meta property="og:description" content="${escape(page.description)}" />\n<meta property="og:url" content="${origin + page.path}" />\n<meta property="og:image" content="${image}" />\n<meta property="og:image:alt" content="${escape(page.alt)}" />\n<meta name="twitter:card" content="summary_large_image" />\n<meta name="twitter:title" content="${escape(page.title)}" />\n<meta name="twitter:description" content="${escape(page.description)}" />\n<meta name="twitter:image" content="${image}" />\n<meta name="twitter:image:alt" content="${escape(page.alt)}" />\n<script type="application/ld+json">${JSON.stringify(graphFor(page)).replaceAll("<", "\\u003c")}</script>`;
